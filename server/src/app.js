import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import { config } from './config/env.js';
import authRoutes from './routes/auth.js';
import campaignRoutes from './routes/campaigns.js';
import volunteerRoutes from './routes/volunteers.js';
import postRoutes from './routes/posts.js';
import commentRoutes from './routes/comments.js';
import adminRoutes from './routes/admin.js';
import contactRoutes from './routes/contact.js';
import userRoutes from './routes/users.js';
import { notFound, errorHandler } from './middleware/errors.js';
import { verifyOrigin } from './middleware/verifyOrigin.js';

const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: config.clientUrl, credentials: true }));
app.use(verifyOrigin);
app.use(express.json({ limit: '100kb' }));
app.use(cookieParser());
if (!config.isProduction) app.use(morgan('dev'));
app.get('/api/v1/health', (_req, res) => res.json({ success: true, data: { status: 'ok' } }));
const authLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: 'draft-7', legacyHeaders: false });
const contactLimiter = rateLimit({ windowMs: 60 * 60 * 1000, limit: 8, standardHeaders: 'draft-7', legacyHeaders: false });
app.use('/api/v1/auth', authLimiter, authRoutes);
app.use('/api/v1/users', userRoutes);
app.use('/api/v1/campaigns', campaignRoutes);
app.use('/api/v1/volunteers', volunteerRoutes);
app.use('/api/v1/posts', postRoutes);
app.use('/api/v1/comments', commentRoutes);
app.use('/api/v1/admin', adminRoutes);
app.use('/api/v1/contact', contactLimiter, contactRoutes);
app.use(notFound, errorHandler);
export default app;
